DEFAULT_PLATFORM_PROFILE_URL = "https://profile.booking-agent.dev/platform-profile.json"


def platform_profile_url() -> str:
    """Public identity URL sent in both USP and UCP Agent headers.

    ``USP_AGENT_PROFILE_URL`` is the only override. Development may point it at
    loopback, but that is not conformant with the RFC 6890 and DNS-rebinding
    checks required of production businesses.
    """
    from . import settings

    return (settings.get("USP_AGENT_PROFILE_URL") or "").strip() or DEFAULT_PLATFORM_PROFILE_URL


